#importazione del modulo math
import math

#uso delle funzioni del modulo

radice_quadrata = math.sqrt(144)
print(f"La radice quadrata di 144 è {radice_quadrata}")
pi_greco = math.pi
print(f"pi greco è circa: {pi_greco}")

#arrotondiamo per difetto
arrotondo1 = math.floor(3.9)
print(f"Arrotondamento per difetto di 3.9 = {arrotondo1}")

#arrotondiamo per eccesso
arrotondo2 = math.ceil(3.1)
print(f"Arrotondamento per eccesso di 3.1 = {arrotondo2}")